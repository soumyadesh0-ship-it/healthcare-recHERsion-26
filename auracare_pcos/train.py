"""Reproducible adult PCOS quiz experiment; run from this project directory.

The label is reported prior diagnosis, NOT verified absence/presence of PCOS.
An untouched grouped holdout evaluates a development-selected model.
"""
from pathlib import Path
import json, time, hashlib, platform, warnings
import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.base import clone
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier
from sklearn.calibration import CalibratedClassifierCV, calibration_curve
from sklearn.model_selection import StratifiedGroupKFold, GridSearchCV
from sklearn.metrics import (accuracy_score, average_precision_score, roc_auc_score,
    precision_score, recall_score, f1_score, brier_score_loss, confusion_matrix,
    roc_curve, precision_recall_curve)
from pcos_data import FEATURES, COMMON_FEATURES, SURVEY_FILE, prepare_survey, prepare_clinical, fingerprints

ROOT = Path(__file__).resolve().parent
SEED = 42
THRESHOLD = 0.5  # Fixed before seeing any test outcomes; not a clinical cutoff.

def dump(path, obj):
    path.write_text(json.dumps(obj, indent=2, allow_nan=False, default=lambda v:
        v.item() if hasattr(v, 'item') else str(v)), encoding='utf-8')

def folds(X, y, groups, n=3, seed=SEED):
    result = list(StratifiedGroupKFold(n_splits=n, shuffle=True, random_state=seed).split(X, y, groups))
    for a, b in result:
        assert not set(groups.iloc[a]) & set(groups.iloc[b]), 'Group leakage'
        assert len(np.unique(y.iloc[b])) == 2, 'Fold lacks one class'
    return result

def specification(name):
    if name == 'random_forest':
        model = Pipeline([('imputer', SimpleImputer(strategy='median', add_indicator=True)),
            ('model', RandomForestClassifier(n_estimators=200, class_weight='balanced',
                                            random_state=SEED, n_jobs=1))])
        grid = {'model__max_depth': [3, 6, None], 'model__min_samples_leaf': [3, 8]}
    else:
        model = Pipeline([('imputer', SimpleImputer(strategy='median', add_indicator=True)),
            ('scale', StandardScaler()),
            ('model', LogisticRegression(max_iter=3000, random_state=SEED))])
        grid = {'model__C': [0.1, 1.0, 10.0], 'model__class_weight': [None, 'balanced']}
    return model, grid

def fit_candidate(name, X, y, groups, n_folds=3):
    model, grid = specification(name)
    cv = folds(X, y, groups, n_folds)
    search = GridSearchCV(model, grid, scoring='average_precision', cv=cv,
                          n_jobs=2, refit=True, error_score='raise')
    search.fit(X, y)
    # Calibration predictions are generated by group-disjoint CV. The outer
    # validation/test data never participate in fitting or hyperparameter choice.
    calibrated = CalibratedClassifierCV(clone(search.best_estimator_), method='sigmoid',
                                       cv=cv, ensemble=False, n_jobs=2)
    calibrated.fit(X, y)
    return calibrated, search.best_params_, float(search.best_score_)

def metrics(y, p):
    pred = np.asarray(p) >= THRESHOLD
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()
    return {'n': len(y), 'positive_labels': int(np.sum(y)),
        'accuracy': float(accuracy_score(y, pred)),
        'precision': float(precision_score(y, pred, zero_division=0)),
        'sensitivity': float(recall_score(y, pred, zero_division=0)),
        'specificity': float(tn / (tn + fp)), 'f1': float(f1_score(y, pred, zero_division=0)),
        'roc_auc': float(roc_auc_score(y, p)),
        'average_precision': float(average_precision_score(y, p)),
        'brier_score': float(brier_score_loss(y, p)),
        'tn': int(tn), 'fp': int(fp), 'fn': int(fn), 'tp': int(tp)}

def intervals(y, p, groups, repeats=1000):
    """Cluster bootstrap of the fixed holdout, conditional on this fitted model."""
    rng = np.random.default_rng(SEED)
    unique = np.unique(groups)
    indices = {g: np.flatnonzero(np.asarray(groups) == g) for g in unique}
    names = ['roc_auc', 'average_precision', 'sensitivity', 'specificity']
    values = {k: [] for k in names}
    y = np.asarray(y)
    for _ in range(repeats):
        sample = np.concatenate([indices[g] for g in rng.choice(unique, len(unique), replace=True)])
        if len(np.unique(y[sample])) < 2:
            continue
        m = metrics(y[sample], p[sample])
        for k in names:
            values[k].append(m[k])
    return {k: [float(v) for v in np.quantile(values[k], [0.025, 0.975])] for k in names}

def charts(results, y, predictions, winner, output):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    plt.rcParams.update({'font.family': 'DejaVu Sans', 'text.color': '#24344D',
                         'axes.labelcolor': '#24344D', 'axes.titlecolor': '#24344D'})
    fig, axes = plt.subplots(2, 2, figsize=(12, 9), constrained_layout=True)
    colors = {'random_forest': '#7FA6CC', 'logistic_regression': '#A491C7'}
    for name in colors:
        fpr, tpr, _ = roc_curve(y, predictions[name])
        axes[0, 0].plot(fpr, tpr, label=f"{name.replace('_',' ')} ({results[name]['roc_auc']:.3f})", color=colors[name], lw=2)
        precision, recall, _ = precision_recall_curve(y, predictions[name])
        axes[0, 1].plot(recall, precision, label=name.replace('_',' '), color=colors[name], lw=2)
        frac, mean = calibration_curve(y, predictions[name], n_bins=5, strategy='quantile')
        axes[1, 0].plot(mean, frac, 'o-', label=name.replace('_',' '), color=colors[name])
    axes[0, 0].plot([0, 1], [0, 1], '--', color='#7FC4A0')
    axes[0, 0].set(xlabel='False positive rate', ylabel='Sensitivity', title='Held-out ROC curves')
    axes[0, 1].axhline(np.mean(y), ls='--', color='#E3A868', label='Positive-label prevalence')
    axes[0, 1].set(xlabel='Recall', ylabel='Precision', title='Held-out precision–recall curves')
    axes[1, 0].plot([0, 1], [0, 1], '--', color='#7FC4A0')
    axes[1, 0].set(xlabel='Mean experimental score', ylabel='Fraction with positive label', title='Calibration: small sample, 5 bins')
    m = results[winner]
    cm = np.array([[m['tn'], m['fp']], [m['fn'], m['tp']]])
    axes[1, 1].imshow(cm, cmap='Purples', vmin=0)
    for i in range(2):
        for j in range(2):
            axes[1, 1].text(j, i, str(cm[i,j]), ha='center', va='center', color='#24344D', fontsize=20,
                               bbox={'facecolor': '#FAF8F5', 'edgecolor': 'none', 'alpha': .9})
    axes[1, 1].set(xticks=[0,1], yticks=[0,1], xticklabels=['Label 0','Label 1'],
                  yticklabels=['Label 0','Label 1'], xlabel='Predicted label', ylabel='Reported label',
                  title=f"Selected: {winner.replace('_',' ')} at 0.5")
    for ax in axes.flat[:3]:
        ax.legend(fontsize=8)
        ax.grid(alpha=.15)
    fig.suptitle('Auracare experimental quiz | labels are reported diagnosis, not verified disease', fontsize=13)
    fig.savefig(output / 'evaluation.png', dpi=160)
    plt.close(fig)

def main():
    start = time.perf_counter()
    out = ROOT / 'outputs'; out.mkdir(exist_ok=True)
    models = ROOT / 'models'; models.mkdir(exist_ok=True)
    prepared, audit = prepare_survey(ROOT / 'data/raw' / SURVEY_FILE)
    prepared.to_csv(out / 'prepared_survey.csv', index=False)
    X, y, groups = prepared[FEATURES], prepared.label.astype(int), prepared.group
    # Fixed first fold is approximately 20% holdout. No split shopping.
    dev_i, test_i = folds(X, y, groups, 5)[0]
    Xdev, ydev, gdev = X.iloc[dev_i].reset_index(drop=True), y.iloc[dev_i].reset_index(drop=True), groups.iloc[dev_i].reset_index(drop=True)
    Xtest, ytest, gtest = X.iloc[test_i].reset_index(drop=True), y.iloc[test_i].reset_index(drop=True), groups.iloc[test_i].reset_index(drop=True)
    outer = folds(Xdev, ydev, gdev, 5, SEED + 1)
    candidates = ['random_forest', 'logistic_regression']
    oof = {}; cv_results = {}; final_models = {}; tuning = {}
    for name in candidates:
        print(f'Nested development validation: {name}', flush=True)
        oof[name] = np.zeros(len(ydev))
        fold_reports = []
        for k, (tr, va) in enumerate(outer):
            model, params, score = fit_candidate(name, Xdev.iloc[tr], ydev.iloc[tr], gdev.iloc[tr])
            p = model.predict_proba(Xdev.iloc[va])[:,1]
            oof[name][va] = p
            fold_reports.append({'fold': k+1, 'parameters': params, 'inner_cv_ap': score,
                                 'outer_metrics': metrics(ydev.iloc[va], p)})
            print(f'  Fold {k+1}/5 complete', flush=True)
        cv_results[name] = {'oof_metrics': metrics(ydev, oof[name]), 'folds': fold_reports}
    winner = max(candidates, key=lambda name: cv_results[name]['oof_metrics']['average_precision'])
    # Selection frozen here, BEFORE any holdout predictions.
    dump(out / 'selection_before_test.json', {'selected_model': winner, 'criterion': 'Nested development OOF average precision', 'threshold': THRESHOLD})
    print(f'Selected before test: {winner}', flush=True)
    predictions = {}; test_results = {}
    for name in candidates:
        model, params, score = fit_candidate(name, Xdev, ydev, gdev, 5)
        final_models[name] = model
        tuning[name] = {'parameters': params, 'inner_cv_ap': score}
        bundle = {'model': model, 'features': FEATURES, 'name': name, 'seed': SEED,
                  'threshold': THRESHOLD, 'scope': 'experimental_adult_18_45',
                  'target': 'self_reported_prior_pcos_diagnosis', 'sklearn_version': sklearn.__version__}
        joblib.dump(bundle, models / f'{name}.joblib', compress=3)
        predictions[name] = model.predict_proba(Xtest)[:,1]
        test_results[name] = metrics(ytest, predictions[name])
    prior = float(ydev.mean())
    test_results['constant_prior_baseline'] = metrics(ytest, np.full(len(ytest), prior))
    dump(models / 'selected_model.json', {'model': winner, 'path': f'{winner}.joblib'})
    labels = prepared[['source_row', 'group', 'label']].copy()
    labels['split'] = 'development'; labels.loc[test_i, 'split'] = 'test'
    labels.to_csv(out / 'split_manifest.csv', index=False)
    pred_frame = pd.DataFrame({'source_row': prepared.iloc[test_i].source_row.to_numpy(), 'reported_label': ytest})
    for name in candidates:
        pred_frame[f'{name}_score'] = predictions[name]
    pred_frame.to_csv(out / 'test_predictions.csv', index=False)
    pd.DataFrame({'source_row': prepared.iloc[dev_i].source_row.to_numpy(), 'reported_label': ydev, **oof}).to_csv(out / 'development_oof_predictions.csv', index=False)
    # Exploratory transfer test: separate seven-feature model, not the main model.
    # No ambiguous clinical menstrual codes are mapped. Its data are not used for
    # fitting, calibration, selection, thresholds, or any performance claims.
    print('Running separate seven-feature transfer stress test', flush=True)
    cg = fingerprints(Xdev, COMMON_FEATURES)
    transfer_model, transfer_params, _ = fit_candidate(winner, Xdev[COMMON_FEATURES], ydev, cg, 5)
    clinical = prepare_clinical(ROOT / 'data/raw/PCOS_data.csv')
    survey_profiles = set(fingerprints(prepared, COMMON_FEATURES))
    overlap = clinical.group.isin(survey_profiles)
    clinical_eval = clinical[~overlap]
    transfer = {'note': 'Different-source stress test of an ablated seven-feature model; NOT external validation of the main eight-feature quiz. Clinical label provenance remains unverified.',
        'feature_semantics_warning': 'Clinical hair growth/skin darkening fields may use clinician assessments; survey fields are self-reported. No period code mapping assumed.',
        'features': COMMON_FEATURES, 'fitted_on': 'survey development only', 'parameters': transfer_params,
        'clinical_rows_available': len(clinical), 'identical_survey_profiles_excluded': int(overlap.sum()),
        'metrics': metrics(clinical_eval.label, transfer_model.predict_proba(clinical_eval[COMMON_FEATURES])[:,1])}
    dump(out / 'transfer_stress_test.json', transfer)
    # Permutation importance is descriptive, never causal or clinical evidence.
    from sklearn.inspection import permutation_importance
    importance = permutation_importance(final_models[winner], Xtest, ytest,
        scoring='average_precision', n_repeats=20, random_state=SEED, n_jobs=2)
    pd.DataFrame({'feature': FEATURES, 'ap_drop_mean': importance.importances_mean,
                  'ap_drop_std': importance.importances_std}).sort_values('ap_drop_mean', ascending=False).to_csv(out/'permutation_importance.csv', index=False)
    subgroup = {}
    age_bin = pd.cut(Xtest.age, [17,25,35,45], labels=['18–25','26–35','36–45'])
    for band in age_bin.cat.categories:
        mask = age_bin == band
        subgroup[band] = metrics(ytest[mask], predictions[winner][mask]) if ytest[mask].nunique() == 2 else {'n': int(mask.sum()), 'note': 'Insufficient class coverage'}
    audit['raw_file_sha256'] = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((ROOT/'data/raw').glob('*.csv'))}
    audit['main_training_source'] = SURVEY_FILE
    audit['clinical_used_only_for_separate_transfer_stress_test'] = True
    audit['not_pooled'] = ['cleaned clinical repeats','ambiguous-class 125-record survey','allData: incompatible categories','1000-record lab-based dataset','image archive']
    dump(out / 'data_audit.json', audit)
    report = {'selected_model': winner, 'selection_metric': 'Nested development OOF average precision',
        'threshold': THRESHOLD, 'seed': SEED, 'features': FEATURES,
        'target': 'self_reported_prior_pcos_diagnosis',
        'split': {'development_n':len(ydev), 'development_positive':int(ydev.sum()),
                  'test_n':len(ytest), 'test_positive':int(ytest.sum()),
                  'development_groups':gdev.nunique(),'test_groups':gtest.nunique(), 'group_overlap':0},
        'nested_cv': cv_results, 'final_tuning': tuning, 'holdout': test_results,
        'selected_holdout_95pct_cluster_bootstrap_intervals': intervals(ytest, predictions[winner], gtest),
        'holdout_age_subgroups_exploratory': subgroup,
        'versions': {'python': platform.python_version(), 'scikit_learn': sklearn.__version__,
                     'numpy':np.__version__, 'pandas':pd.__version__, 'joblib':joblib.__version__},
        'training_and_evaluation_seconds': round(time.perf_counter()-start,2),
        'limitations': ['Labels are self-report; 0 does not confirm disease absence.',
          'Unknown sampling, consent-for-reuse, source licensing and diagnosis verification.',
          'No patient IDs available for deduplicating people; feature groups are only a proxy.',
          'Adult 18–45 experiment; no adolescent, pregnancy, contraception or prospective validation.',
          'Cross-sectional data cannot validate daily progression or temporal predictions.',
          'Calibration is internal to this sample; scores are not clinical probabilities.',
          'Holdout is small; confidence intervals exclude retraining and sampling-frame uncertainty.']}
    dump(out / 'metrics.json', report)
    charts(test_results, ytest, predictions, winner, out)
    print(json.dumps({'selected':winner, 'split':report['split'], 'holdout':test_results,
                      'seconds':report['training_and_evaluation_seconds']}, indent=2), flush=True)

if __name__ == '__main__':
    main()
